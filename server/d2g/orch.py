"""Orchestrator: one per client project. Holds the cloud credentials and the CA, creates
receivers (cloud-init) and volumes, hands jobs to agents and receivers, builds VMs from volumes.

Network entry: nginx on :443 routes TLS by SNI without decrypting it — ctl.<domain> to this API
(127.0.0.1:8443), rxN.<domain> to the receivers' grey addresses. Agents that cannot reach a
receiver directly (grey IP over Direct Connect or the receiver's own FIP) go through it.
"""
