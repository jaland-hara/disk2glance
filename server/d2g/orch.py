            if ip:
                print(f"# {kind}:\ncurl -fsS -k --pinnedpubkey '{pin}' --connect-to {c['ctl_name']}:443:{ip}:443 "
                      f"https://{c['ctl_name']}/install.sh | sudo sh -s -- {ip} {tok} {a.name}")
