def free_fip(cl, t):
    used = {r["fip_id"] for r in db().execute("SELECT fip_id FROM receivers WHERE state!='deleted'")}
    for fid in t["fip_pool"]:
        if fid in used:
            continue
        if not cl.fip(fid).get("port_id"):
            return fid
    return None


def receiver_add(c, cl, az=None, flavor=None, fip=None, wait=True, target="home"):
    """A receiver VM in the home project, or (target in receiver mode) in another project with its
    account; there it reaches the orchestrator over its public address."""
    from . import targets as T
    t = T.tconf(c, target)
    remote = t["name"] != "home"
    if remote and t["mode"] != "receiver":
        die(f"target {target} is in {t['mode']} mode: its jobs use the home receivers")
    ctl_addr = c.get("public_ip") if remote else c["grey_ip"]
    if remote and not ctl_addr:
        die("receivers in other projects need the orchestrator's public address (d2g setup --public-ip)")
    names = {r["name"] for r in db().execute("SELECT name FROM receivers")}
    i = 1
    while f"rx{i}" in names:
        i += 1
    name, az, flavor = f"rx{i}", az or t["az"], flavor or t["rx_flavor"]
    tok = secrets.token_urlsafe(24)
    db().execute("INSERT INTO receivers (name, az, flavor, state, token_hash, token_exp, created, target) "
                 "VALUES (?,?,?,'creating',?,?,?,?)", (name, az, flavor, h(tok), now() + 3 * TOKEN_TTL, now(), t["name"]))
    try:
        if remote:
            # its own SG there: 443 from the sources and from the orchestrator (SNI path via the FIP);
            # on the orchestrator: 443 from the router of the receiver's network (it joins through it)
            cl.ensure_sg(RX_SG, "d2g receivers: 443 from the orchestrator and allowed sources",
                         [("tcp", 443, f"{c['public_ip']}/32")] + [("tcp", 443, x) for x in t["allow"]])
            T.open_ctl_for(c, T.egress_ips(cl, t["network"]))
        else:
            # the receiver joins and sends heartbeats to the orchestrator's grey address
            sgs = cl.call("GET", "network", f"/security-groups?name={RX_SG}")["security_groups"]
            if sgs:
                T.open_ctl_for(c, [f"sg:{sgs[0]['id']}"])
        log(f"receiver {name} in {t['name']}: boot volume {t['rx_volume_gb']} GB {t['rx_volume_type']} from image {t['rx_image']}")
        vid = cl.create_volume(f"d2g-{name}-boot", t["rx_volume_gb"], t["rx_volume_type"], az, image=t["rx_image"],
                               meta={"d2g_receiver": name})
        cl.wait_vol(vid, "available")
        # one NIC queue per vCPU (Nova reads image properties of a boot volume from the volume)
        cl.vol_action(vid, {"os-set_image_metadata": {"metadata": {"hw_vif_multiqueue_enabled": "true"}}})
        sid = cl.create_server(f"d2g-{c['install_id']}-{name}", flavor, az, t["network"], vid, [RX_SG] + t["rx_sg"],
                               key=t["rx_key"] or None, user_data=user_data(c, name, tok, ctl_addr), delete_vol=True,
                               meta={"d2g_receiver": name, "d2g_install": c["install_id"]})
        db().execute("UPDATE receivers SET server_id=? WHERE name=?", (sid, name))
        s = cl.wait_server(sid)
        ip = cl.server_ip(s, t["network"])
        fid = free_fip(cl, t) if fip == "auto" else fip
        fip_addr = None
        if fid:
            fip_addr = cl.fip_attach(fid, sid)["floating_ip_address"]
            if remote:
                T.open_ctl_for(c, [fip_addr])
        db().execute("UPDATE receivers SET grey_ip=?, fip_id=?, fip=? WHERE name=?", (ip, fid, fip_addr, name))
        write_nginx(c)
        event(actor(), f"receiver {name}: server {sid} {flavor} in {t['name']}/{az}, {ip}{', FIP ' + fip_addr if fip_addr else ''}")
        log(f"receiver {name}: server {sid} ACTIVE, {ip}{', FIP ' + fip_addr if fip_addr else ''}; waiting for it to join")
    except BaseException:
        db().execute("UPDATE receivers SET state='failed' WHERE name=?", (name,))
        raise
    if wait:
        t0 = time.time()
        while time.time() - t0 < 900:
            r = db().execute("SELECT state FROM receivers WHERE name=?", (name,)).fetchone()
            if r["state"] == "up":
                log(f"receiver {name} is up ({time.time() - t0:.0f} s after boot)")
                return name
            time.sleep(5)
        die(f"receiver {name} did not come up in 15 min: see /var/log/d2g-install.log and cloud-init logs on {ip}")
    return name


def rx_up(r):
    return r["state"] == "up" and r["last_seen"] and now() - r["last_seen"] < 60


def cmd_receiver(a):
    c = conf()
    if a.op == "list":
        for r in db().execute("SELECT * FROM receivers WHERE state!='deleted' ORDER BY created"):
            n = db().execute("SELECT count(*) FROM jobs WHERE receiver=? AND state NOT IN ('finished','deleted')",
                             (r["name"],)).fetchone()[0]
            st = r["state"] if r["state"] != "up" or rx_up(r) else "down"
            seen = f"{now() - r['last_seen']} s ago" if r["last_seen"] else "never"
            info = json.loads(r["info"] or "{}")
            print(f"{r['name']:<5} {st:<9} {rx_dns(c, r['name']):<22} {(r['target'] or 'home'):<10} {(r['flavor'] or '') + (' local' if r['local'] else ''):<16} {r['az']:<5} grey {r['grey_ip'] or '-':<14} "
                  f"FIP {r['fip'] or '-':<15} volumes {n}/{c['max_volumes']}  load {info.get('load', '-')}  seen {seen}")
        return
    from . import targets as T
    if a.op == "add":
        receiver_add(c, T.cloud_for(a.target), a.az, a.flavor, a.fip, wait=not a.no_wait, target=a.target or "home")
    elif a.op == "delete":
        r = db().execute("SELECT * FROM receivers WHERE name=?", (a.name,)).fetchone() or die("no such receiver")
        if r["local"]:
            die("rx0 is the receiver on this VM: it goes away with the orchestrator")
        busy = db().execute("SELECT id FROM jobs WHERE receiver=? AND state NOT IN ('finished','deleted')", (a.name,)).fetchall()
        if busy:
            die(f"receiver {a.name} still serves jobs {[x['id'] for x in busy]}: finish or delete them first")
        cl = T.cloud_for(r["target"])
        if r["fip_id"]:
            try:
                cl.fip_detach(r["fip_id"])
            except Exception as ex:  # noqa: BLE001
                log(f"FIP {r['fip']}: {ex}")
        if r["server_id"]:
            cl.delete_server(r["server_id"])
        db().execute("UPDATE receivers SET state='deleted' WHERE name=?", (a.name,))
        write_nginx(c)
        event(actor(), f"receiver {a.name}: deleted")
        print(f"receiver {a.name}: deleted (FIP returned to the pool)")


