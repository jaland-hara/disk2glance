def actor():
    """who is acting: 'admin' (CLI) or 'ui:<name>' (the web interface runs the CLI)."""
    return os.environ.get("D2G_ACTOR", "admin")


def event(who, what):
    db().execute("INSERT INTO events VALUES (?,?,?)", (now(), who, what))


def h(tok):
    return hashlib.sha256(tok.encode()).hexdigest()


def rx_dns(c, name):
    return f"{name}.{c['domain']}"


def nparts(j):
    return (j["disk_bytes"] + j["part_bytes"] - 1) // j["part_bytes"]


# --- nginx: SNI routing on :443 -----------------------------------------------------------------
def write_nginx(c):
    lines = ["# generated by d2g (orchestrator) — do not edit", "map $ssl_preread_server_name $d2g_upstream {"]
    for r in db().execute("SELECT name, grey_ip, local FROM receivers WHERE grey_ip IS NOT NULL AND state!='deleted'"):
        up = f"127.0.0.1:{LOCAL_RX_PORT}" if r["local"] else f"{r['grey_ip']}:443"
        lines.append(f"    {rx_dns(c, r['name'])} {up};")
    lines += [f"    {c['ctl_name']} 127.0.0.1:{c['api_port']};", f"    default 127.0.0.1:{c['api_port']};", "}",
              "server {", "    listen 443;", "    ssl_preread on;", "    proxy_pass $d2g_upstream;",
              "    proxy_protocol on;", "    proxy_connect_timeout 10s;", "    proxy_timeout 600s;", "}", ""]
    new = "\n".join(lines)
    old = open(NGINX_CONF).read() if os.path.exists(NGINX_CONF) else ""
    if new != old:
        with open(NGINX_CONF, "w") as f:
            f.write(new)
        r = subprocess.run(["nginx", "-t"], capture_output=True, text=True)
        if r.returncode:
            raise RuntimeError(f"nginx -t: {r.stderr.strip()}")
        subprocess.run(["systemctl", "reload-or-restart", "nginx"], check=True)


# --- HTTPS API ---------------------------------------------------------------------------------------
class OrchHandler(C.Handler):
    def who(self):
        """('agent'|'rx', name) for a valid client certificate, else (None, None)."""
        cn, serial = self.peer_cert()
        if not cn:
            return None, None
        if cn.startswith("rx:"):
            r = db().execute("SELECT cert_serial FROM receivers WHERE name=? AND state!='deleted'", (cn[3:],)).fetchone()
            return ("rx", cn[3:]) if r and C.same_serial(r["cert_serial"], serial) else (None, None)
        a = db().execute("SELECT cert_serial, revoked FROM agents WHERE name=?", (cn,)).fetchone()
        if not a or a["revoked"] or not C.same_serial(a["cert_serial"], serial):
            return None, None
        db().execute("UPDATE agents SET last_seen=?, peer=? WHERE name=?", (now(), self.peer_ip, cn))
        return "agent", cn

    def route(self, method, p):
        c = self.server.conf
        if getattr(self.connection, "d2g_ui", False):
            from . import ui
            return ui.handle(self, method, p)
        if p == ["v1", "ping"]:
            return self.reply(200, {"orchestrator": c["ctl_name"]})
        if p == ["v1", "ca"]:
            with open(f"{PKI}/ca.crt") as f:
                return self.reply(200, {"ca": f.read()})
        if p == ["install.sh"]:
            return self.reply(200, raw=install_script(c).encode(), ctype="text/x-shellscript")
        if p[:2] == ["v1", "pkg"] and len(p) == 3 and p[2] in ("agent.tar.gz", "server.tar.gz"):
            pat = "disk2glance-*.tar.gz" if p[2] == "agent.tar.gz" else "d2g-server-*.tar.gz"
            files = sorted(glob.glob(os.path.join(C.PKG, pat)))
            return self.send_file(files[-1]) if files else self.reply(404, {"error": "no package"})
        if p == ["v1", "enroll"] and method == "POST":
            return self.enroll(self.body_json())
        if p == ["v1", "rx", "join"] and method == "POST":
            return self.rx_join(self.body_json())
        kind, name = self.who()
        if kind == "rx" and p == ["v1", "rx", "heartbeat"] and method == "POST":
            return self.reply(200, rx_heartbeat(c, name, self.body_json()))
        if kind == "agent":
            if p == ["v1", "agent", "job"] and method == "GET":
                return self.agent_job(c, name)
            if p == ["v1", "agent", "command"] and method == "GET":
                a = db().execute("SELECT * FROM agents WHERE name=?", (name,)).fetchone()
                if not a["command"]:
                    return self.reply(200, {})
                return self.reply(200, {"id": a["command_id"], "command": a["command"], "threads": a["threads"]})
            if p == ["v1", "agent", "report"] and method == "POST":
                b = self.body_json()
                a = db().execute("SELECT command_id FROM agents WHERE name=?", (name,)).fetchone()
                db().execute("UPDATE agents SET last_report=?, report_at=? WHERE name=?", (json.dumps(b), now(), name))
                if b.get("id") and b["id"] == a["command_id"]:
                    db().execute("UPDATE agents SET command=NULL, command_id=NULL WHERE name=?", (name,))
                event(name, f"report: {b.get('command', 'pass')} rc={b.get('rc')} {b.get('summary', '')}"[:400])
                return self.reply(200, {})
        self.drain()
        return self.reply(401 if kind is None else 404, {"error": "not found or not allowed"})

    def enroll(self, b):
        name, token = b.get("name", ""), b.get("token", "")
        row = db().execute("SELECT * FROM agents WHERE name=?", (name,)).fetchone()
        if not row or not row["token_hash"] or not secrets.compare_digest(row["token_hash"], h(token)) \
                or row["token_exp"] < now():
            log(f"enroll {name!r} from {self.peer_ip}: bad or expired token")
            return self.reply(403, {"error": "bad or expired token"})
        serial, crt = C.sign_csr(PKI, b.get("csr", ""), name, "clientAuth")
        db().execute("UPDATE agents SET token_hash=NULL, token_exp=NULL, enrolled_at=?, cert_serial=?, revoked=0, "
                     "inventory=?, last_seen=?, peer=? WHERE name=?",
                     (now(), serial, json.dumps(b.get("inventory") or {}), now(), self.peer_ip, name))
        event(name, f"enrolled from {self.peer_ip}")
        log(f"agent {name} enrolled from {self.peer_ip}")
        return self.reply(200, {"cert": crt})

    def rx_join(self, b):
        name, token = b.get("name", ""), b.get("token", "")
        r = db().execute("SELECT * FROM receivers WHERE name=?", (name,)).fetchone()
        if not r or not r["token_hash"] or not secrets.compare_digest(r["token_hash"], h(token)) \
                or r["token_exp"] < now():
            log(f"receiver join {name!r} from {self.peer_ip}: bad or expired token")
            return self.reply(403, {"error": "bad or expired token"})
        dns = rx_dns(self.server.conf, name)
        serial, crt = C.sign_csr(PKI, b.get("csr", ""), "rx:" + name, "serverAuth,clientAuth", dns=[dns], days=825)
        db().execute("UPDATE receivers SET token_hash=NULL, token_exp=NULL, cert_serial=?, state='joined' WHERE name=?",
                     (serial, name))
        event("rx:" + name, f"joined from {self.peer_ip}")
        log(f"receiver {name} joined from {self.peer_ip}")
        return self.reply(200, {"cert": crt, "dns": dns})

    def agent_job(self, c, name):
        j = db().execute("SELECT * FROM jobs WHERE agent=? AND state IN ('ready','receiving','synced') "
                         "ORDER BY created DESC LIMIT 1", (name,)).fetchone()
        if not j:
            busy = db().execute("SELECT state FROM jobs WHERE agent=? AND state IN ('attaching','finishing','deleting')",
                                (name,)).fetchone()
            return self.reply(409 if busy else 404, {"error": f"job is {busy['state']}" if busy else "no job"})
        r = db().execute("SELECT * FROM receivers WHERE name=?", (j["receiver"],)).fetchone()
        a = db().execute("SELECT path, threads FROM agents WHERE name=?", (name,)).fetchone()
        addrs = [["rx-grey", r["grey_ip"]]]
        if r["fip"]:
            addrs.append(["rx-fip", r["fip"]])
        if c.get("public_ip"):
            addrs.append(["ctl", c["public_ip"]])
        addrs.append(["ctl-grey", c["grey_ip"]])
        if a["path"] != "auto":
            addrs = [x for x in addrs if x[0] == a["path"]] or addrs
        return self.reply(200, {"id": j["id"], "disk_bytes": j["disk_bytes"], "part_bytes": j["part_bytes"],
                                "block_bytes": j["part_bytes"] // BLOCKS_PER_PART, "state": j["state"],
                                "pass_no": j["pass_no"], "threads": a["threads"],
                                "receiver": {"name": rx_dns(c, r["name"]), "addrs": addrs}})


def rx_heartbeat(c, name, b):
    """Receiver state in, job specs out."""
    db().execute("UPDATE receivers SET last_seen=?, state=CASE WHEN state IN ('creating','joined','up','down') "
                 "THEN 'up' ELSE state END, info=? WHERE name=?",
                 (now(), json.dumps({k: b.get(k) for k in ("load", "root", "devices")}), name))
    rep = b.get("jobs") or {}
    devs = set(b.get("devices") or [])
    specs = []
    for j in db().execute("SELECT * FROM jobs WHERE receiver=? AND state IN "
                          "('attaching','ready','receiving','synced','finishing','deleting')", (name,)).fetchall():
        a = db().execute("SELECT cert_serial, revoked FROM agents WHERE name=?", (j["agent"],)).fetchone()
        st = "active" if j["state"] in ACTIVE else "release"
        if j["state"] == "attaching" and j["serial"] not in devs:
            continue
        specs.append({"id": j["id"], "agent": j["agent"], "agent_serial": "" if not a or a["revoked"] else a["cert_serial"],
                      "serial": j["serial"], "disk_bytes": j["disk_bytes"], "part_bytes": j["part_bytes"], "state": st})
        r = rep.get(j["id"])
        if not r:
            continue
        upd = {"rx_state": r["state"], "rx_released": r["released"], "parts": r["parts"], "pass_no": r["pass_no"],
               "pass_start": r["pass_start"], "pass_parts": r["pass_parts"], "last_part": r["last_part"],
               "synced_at": r["synced_at"], "synced_snapshot": r["synced_snapshot"]}
        if j["state"] in ACTIVE:
            upd["state"] = r["state"]
            if j["state"] == "attaching" and j["autostart"]:
                queue_command(j["agent"], "sync")
                event("orchestrator", f"job {j['id']}: volume is served by {name}, first pass queued")
        db().execute("UPDATE jobs SET " + ", ".join(f"{k}=?" for k in upd) + " WHERE id=?", (*upd.values(), j["id"]))
    return {"jobs": specs}


def queue_command(agent, command):
    cid = secrets.token_hex(4)
    db().execute("UPDATE agents SET command=?, command_id=?, command_at=? WHERE name=?", (command, cid, now(), agent))
    return cid


def scheduler():
    """Delta passes by schedule (job sync_every)."""
    while True:
        try:
            for j in db().execute("SELECT * FROM jobs WHERE sync_every>0 AND state='synced'").fetchall():
                a = db().execute("SELECT command FROM agents WHERE name=?", (j["agent"],)).fetchone()
                if a and not a["command"] and now() - (j["synced_at"] or 0) >= j["sync_every"]:
                    queue_command(j["agent"], "sync")
                    event("orchestrator", f"job {j['id']}: scheduled pass queued")
        except Exception as ex:  # noqa: BLE001
            log(f"scheduler: {ex}")
        time.sleep(30)


def install_script(c):
    pin = C.pubkey_pin(f"{PKI}/ctl.crt")
    return f"""#!/bin/sh
# disk2glance agent installer, generated by the d2g orchestrator {c['ctl_name']}
# usage: curl ... https://{c['ctl_name']}/install.sh | sudo sh -s -- ADDRESS TOKEN NAME
set -eu
ADDR=$1 TOKEN=$2 NAME=$3
CTL={c['ctl_name']}
PIN='{pin}'
[ "$(id -u)" = 0 ] || {{ echo "run as root" >&2; exit 1; }}
d=$(mktemp -d)
cd "$d"
curl -fsS -k --pinnedpubkey "$PIN" --connect-to "$CTL:443:$ADDR:443" "https://$CTL/v1/pkg/agent.tar.gz" -o agent.tgz
tar xzf agent.tgz
cd disk2glance-*
./install.sh
/opt/disk2glance/bin/disk2rx --enroll --name "$NAME" --server "$CTL" --connect "$ADDR" --pin "$PIN" --token "$TOKEN"
cd /
rm -rf "$d"
"""


def cmd_serve(a):
    import ssl
    c = conf()
    db_init()
    db().execute("UPDATE tasks SET state='interrupted', finished=? WHERE state='running'", (now(),))
    srv = C.Server(("127.0.0.1", c["api_port"]), OrchHandler)
    srv.ctx = C.server_ctx(f"{PKI}/ctl.crt", f"{PKI}/ctl.key", f"{PKI}/ca.crt")
    # browsers come by IP (no SNI) or any other name: they get the UI and its own certificate
    ui_ctx = C.server_ctx(f"{PKI}/ui.crt", f"{PKI}/ui.key", f"{PKI}/ca.crt")
    ui_ctx.verify_mode = ssl.CERT_OPTIONAL if c.get("ui_mtls") else ssl.CERT_NONE

    def sni(sock, name, _ctx):
        if name != c["ctl_name"]:
            sock.context = ui_ctx
            sock.d2g_ui = True
    srv.ctx.sni_callback = sni
    srv.conf = c
    log(f"orchestrator {c['ctl_name']} on 127.0.0.1:{c['api_port']} (behind nginx :443), project {c.get('project', '?')}")
    C.serve(srv, a.workers or 2, in_parent=scheduler)


# --- CLI: setup -----------------------------------------------------------------------------------
def cmd_setup(a):
    os.makedirs(C.ETC, mode=0o755, exist_ok=True)
    os.makedirs(C.VAR, mode=0o700, exist_ok=True)
    c = conf() if os.path.exists(CONF) else {}
    md = metadata()
    cl = Cloud()
    me = cl.server(md["uuid"])
    c.setdefault("install_id", secrets.token_hex(3))
    c.setdefault("domain", f"{c['install_id']}.d2g")
    c["ctl_name"] = f"ctl.{c['domain']}"
    c["server_id"] = md["uuid"]
    c["project"] = cl.project
    c["az"] = a.az or c.get("az") or md["availability_zone"]
    c["network"] = a.network or c.get("network") or next(iter(me["addresses"]))
    c["grey_ip"] = cl.server_ip(me, c["network"])
    if a.public_ip is not None:
        c["public_ip"] = a.public_ip
    c.setdefault("public_ip", "")
    c.setdefault("api_port", 8443)
    if not c.get("rx_image") and not a.rx_image:
        vols = me.get("os-extended-volumes:volumes_attached") or []
        for v in vols:
            meta = cl.vol(v["id"]).get("volume_image_metadata") or {}
            if meta.get("image_id"):
                c["rx_image"] = meta["image_id"]
                break
    for k in ("rx_image", "rx_flavor", "rx_volume_type", "rx_key"):
        if getattr(a, k):
            c[k] = getattr(a, k)
    c.setdefault("rx_flavor", "STD3-4-4")
    c.setdefault("rx_volume_type", "ceph-ssd")
    c.setdefault("rx_volume_gb", 20)
    c.setdefault("rx_key", "")
    if a.rx_sg:
        c["rx_sg"] = a.rx_sg
    c.setdefault("rx_sg", [])
    if a.allow:
        c["allow"] = sorted(set(c.get("allow", []) + a.allow))
    c.setdefault("allow", [])
    if a.fip_pool:
        c["fip_pool"] = sorted(set(c.get("fip_pool", []) + a.fip_pool))
    c.setdefault("fip_pool", [])
    c.setdefault("max_volumes", 20)
    c.setdefault("part_mb", 64)
    c.setdefault("vm_sg", ["default"])
    if a.ui_allow:
        c["ui_allow"] = sorted(set(c.get("ui_allow", []) + a.ui_allow))
    c.setdefault("ui_allow", [])
    if a.ui_mtls:
        c["ui_mtls"] = a.ui_mtls == "on"
    c.setdefault("ui_mtls", False)
    C.ca_init(PKI, f"d2g CA {c['domain']}")
    if not os.path.exists(f"{PKI}/ctl.crt"):
        csr = C.new_key_csr(f"{PKI}/ctl.key", c["ctl_name"])
        _, crt = C.sign_csr(PKI, csr, c["ctl_name"], "serverAuth", dns=[c["ctl_name"]], days=825)
        with open(f"{PKI}/ctl.crt", "w") as f:
            f.write(crt)
    C.save_json(CONF, c, 0o644)
    db_init()
    if a.local_receiver:
        local_receiver(c, cl, me)
    rules = [("tcp", 443, f"{c['grey_ip']}/32")] + [("tcp", 443, x) for x in c["allow"]]
    cl.ensure_sg(RX_SG, "d2g receivers: 443 from the orchestrator and allowed sources", rules)
    write_nginx(c)
    print(f"orchestrator {c['ctl_name']}: grey {c['grey_ip']}, public {c['public_ip'] or '-'}, "
          f"network {c['network']}, AZ {c['az']}")
    print(f"receivers: {c['rx_flavor']}, image {c.get('rx_image')}, {c['rx_volume_gb']} GB {c['rx_volume_type']}, "
          f"SG {RX_SG} (443 from {c['grey_ip']} {' '.join(c['allow'])}), FIP pool {c['fip_pool'] or '-'}")
    print(f"pin of {c['ctl_name']}: {C.pubkey_pin(PKI + '/ctl.crt')}")
    from . import ui
    fp = ui.ui_cert(PKI, c)
    addr = c["public_ip"] or c["grey_ip"]
    print(f"web UI: https://{addr}/  certificate SHA-256 {fp}")
    print(f"  allowed from: {' '.join(c['ui_allow']) or 'nowhere yet (d2g setup --ui-allow CIDR)'}; "
          f"admin certificate {'required' if c['ui_mtls'] else 'not required'}; admins: d2g admin add NAME")


def local_receiver(c, cl, me):
    """Receiver rx0 on this VM: job volumes are attached here, nginx routes rx0.<domain> to it."""
    from . import recv
    if db().execute("SELECT 1 FROM receivers WHERE name='rx0' AND state!='deleted'").fetchone():
        return
    csr = C.new_key_csr(f"{PKI}/rx.key", "rx:rx0")
    serial, crt = C.sign_csr(PKI, csr, "rx:rx0", "serverAuth,clientAuth", dns=[rx_dns(c, "rx0")], days=825)
    with open(f"{PKI}/rx.crt", "w") as f:
        f.write(crt)
    flavor = (me.get("flavor") or {}).get("original_name") or (me.get("flavor") or {}).get("id", "")
    db().execute("INSERT OR REPLACE INTO receivers (name, server_id, az, flavor, grey_ip, state, cert_serial, created, local) "
                 "VALUES ('rx0',?,?,?,?,'joined',?,?,1)", (c["server_id"], c["az"], flavor, c["grey_ip"], serial, now()))
    C.save_json(recv.CONF, {"name": "rx0", "dns": rx_dns(c, "rx0"), "ctl_name": c["ctl_name"], "ctl_addr": "127.0.0.1",
                            "bind": "127.0.0.1", "port": LOCAL_RX_PORT, "max_inflight": 4 * (os.cpu_count() or 1),
                            "max_per_job": 16})
    recv.db.init()
    event(actor(), "receiver rx0: local (on the orchestrator VM)")
    print(f"local receiver rx0 ({rx_dns(c, 'rx0')}): job volumes are attached to this VM")


