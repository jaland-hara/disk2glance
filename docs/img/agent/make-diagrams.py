# 3. Один проход ----------------------------------------------------------------------------------------
s = Svg(1200, 700, "Один проход по шагам", "Управление идёт через оркестратор, данные — напрямую на приёмник")
L = {"agent": 200, "ctl": 600, "rx": 1000}
for k, (name, sub, c) in {"agent": ("Агент", "исходная ВМ", GREY), "ctl": ("Оркестратор", "", BLUE), "rx": ("Приёмник", "", BLUE)}.items():
    s.box(L[k] - 110, 95, 220, 56, name, [sub] if sub else [], c=c)
    line(s, L[k], 151, L[k], 670, "#B8C0CC", dash=True)
y = 190
steps = [("agent", "ctl", "1. Задание: том, адреса приёмника, размер части"),
         ("agent", "rx", "2. Проверка пути: первый ответивший адрес приёмника"),
         ("agent", None, "3. sync, снапшоты всех смонтированных ФС"),
         ("agent", "rx", "4. Начало прохода: время снапшота"),
         ("rx", "agent", "5. Журнал: MD5 блоков, которые уже есть на томе"),
         ("agent", "rx", "6. Части с изменёнными блоками, 8–32 потока"),
         ("agent", "rx", "7. Сверка: MD5 списков блоков всех частей"),
         ("rx", "agent", "8. «Синхронизировано» или список частей для повтора"),
         ("agent", None, "9. Удаление снапшотов, возврат настроек"),
         ("agent", "ctl", "10. Отчёт: сколько передано, за сколько, ошибки")]
for a, b, label in steps:
    if b is None:
        rect(s, L[a] - 10, y - 14, 20, 28, "#F1F3F6", LINE)
        s.t(L[a] + 24, y + 5, label, 14, INK)
    else:
        x1, x2 = L[a], L[b]
        s.arrow([(x1 + (8 if x2 > x1 else -8), y), (x2 - (8 if x2 > x1 else -8), y)], c=BLUE if "rx" in (a, b) else LINE, width=2)
        mx = (x1 + x2) / 2
        w = len(label) * 7.3 + 14
        s.o.append(f'<rect x="{mx - w / 2}" y="{y - 26}" width="{w}" height="19" rx="4" fill="#FFFFFF"/>')
        s.t(mx, y - 12, label, 13.5, INK, anchor="middle")
    y += 48
s.save(OUT + "/pass.svg")

