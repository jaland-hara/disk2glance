def rect(s, x, y, w, h, fill, stroke, rx=4):
    s.o.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}" stroke="{stroke}" stroke-width="1.5"/>')


def line(s, x1, y1, x2, y2, c=LINE, w=1.5, dash=False):
    da = ' stroke-dasharray="6 5"' if dash else ""
    s.o.append(f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{c}" stroke-width="{w}"{da}/>')


