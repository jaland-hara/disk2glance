# 3. Этапы переноса ------------------------------------------------------------------------------------
s = Svg(1200, 440, "Этапы переноса одной ВМ",
        "Исходная ВМ всё это время работает; приложение останавливают только перед последней дельтой, если нужно")
steps = [("Агент", ["команда из интерфейса,", "запуск на исходной ВМ"], GREY),
         ("Задание", ["том по размеру диска", "у приёмника"], BLUE),
         ("Первый проход", ["все занятые блоки", "снапшот → том"], BLUE),
         ("Дельты", ["только изменения,", "по расписанию"], BLUE),
         ("Создать ВМ", ["том отключается,", "ВМ создаётся с тома"], GREEN),
         ("Удалить агента", ["с исходной ВМ", "(на копии выключен)"], GREY)]
bw, gap, x = 168, 26, 32
boxes = []
for i, (n, l, c) in enumerate(steps):
    bx = s.box(x, 120, bw, 84, n, l, c=c)
    s.num(x + 14, 120, i + 1, c if c != GREY else LINE)
    boxes.append(bx)
    x += bw + gap
for a, b in zip(boxes, boxes[1:]):
    s.arrow([a.r(), b.l()])
d = boxes[3]
s.arrow([d.b(0.3), (d.b(0.3)[0], 240), (d.b(0.7)[0], 240), d.b(0.7)], c=BLUE)
s.t(d.b()[0], 258, "повторять", 12, BLUE, anchor="middle")
s.t(32, 316, "Где смотреть:", 13, INK, bold=True)
s.t(32, 340, "1 — вкладка «Исходные ВМ»;  2–4 — «Задания» и «Обзор»;  5 — «Задания» → «Создать ВМ», ход — «Журнал»;", 13, MUT)
s.t(32, 360, "6 — «Исходные ВМ» → «Удалить агента».", 13, MUT)
s.t(32, 396, "После шага 5 новые проходы по этому заданию невозможны: том уже стал диском новой ВМ.", 13, ORANGE)
s.save(OUT + "/stages.svg")

